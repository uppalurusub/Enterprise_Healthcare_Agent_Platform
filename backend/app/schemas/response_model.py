"""
models/response_model.py

Response models for Enterprise Healthcare Agent Platform
"""

from typing import Optional

from pydantic import BaseModel, ConfigDict, Field


# -------------------------------------------------------------------------
# Individual Agent Response
# -------------------------------------------------------------------------

class AgentResponse(BaseModel):
    """
    Standard response returned by an individual AutoGen agent.
    """

    agent_name: str = Field(
        ...,
        description="Name of the AI agent."
    )

    summary: str = Field(
        ...,
        description="Summary generated by the agent."
    )

    execution_time_seconds: float = Field(
        ...,
        description="Execution time of the agent."
    )


# -------------------------------------------------------------------------
# Human Review
# -------------------------------------------------------------------------

class HumanReview(BaseModel):
    """
    Human-in-the-Loop review details.
    """

    required: bool = Field(
        ...,
        description="Whether human review was required."
    )

    status: str = Field(
        ...,
        description="Approval status."
    )

    reviewer_comments: Optional[str] = Field(
        default=None,
        description="Optional reviewer comments."
    )


# -------------------------------------------------------------------------
# Metadata
# -------------------------------------------------------------------------

class Metadata(BaseModel):
    """
    Response metadata.
    """

    request_id: str = Field(
        ...,
        description="Unique request identifier."
    )

    session_id: Optional[str] = Field(
        default=None,
        description="Client session identifier."
    )

    generated_at: Optional[str] = Field(
        ...,
        description="UTC timestamp."
    )

    total_execution_time_seconds: Optional[float] = Field(
        ...,
        description="Overall workflow execution time."
    )


